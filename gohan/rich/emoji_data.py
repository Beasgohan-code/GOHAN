def all_pairs() -> tuple[tuple[str, str], ...]:
    """Every ``(emoji, custom_id)`` pair from every pack, de-duplicated by id."""
    seen: set[str] = set()
    out: list[tuple[str, str]] = []
    for pack in PACKS.values():
        for char, custom_id in pack:
            if custom_id in seen:
                continue
            seen.add(custom_id)
            out.append((char, custom_id))
    return tuple(out)


def count() -> int:
    return len(all_pairs())


